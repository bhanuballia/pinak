# relationships/ai_relationship_analysis.py

class AIRelationshipAnalysis:

    def interpret(
        self,
        relationship
    ):

        if relationship == "Great Friend":

            return (
                "Strong supportive "
                "planetary alliance."
            )

        if relationship == "Great Enemy":

            return (
                "Severe karmic conflict "
                "between planets."
            )

        return (
            "Moderate planetary "
            "interaction."
        )
