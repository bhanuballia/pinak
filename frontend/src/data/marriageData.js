export const getSingleDigit = (num) => {
    let d = Math.abs(num);
    while (d > 9) {
        d = d.toString().split('').reduce((sum, digit) => sum + parseInt(digit), 0);
    }
    return d;
};

export const predictMarriageYears = (dobStr) => {
    if (!dobStr || dobStr.includes('undefined')) return null;

    let day, month, year;
    if (dobStr.includes('-')) {
        [year, month, day] = dobStr.split('-').map(num => parseInt(num));
    } else if (dobStr.includes('/')) {
        [day, month, year] = dobStr.split('/').map(num => parseInt(num));
    }

    if (!day || !month || !year || isNaN(day) || isNaN(month) || isNaN(year)) return null;

    const birthNumber = getSingleDigit(day);
    const lifePathNumber = getSingleDigit(day + month + year);
    const rules = NUMEROLOGY_MARRIAGE_RULES[birthNumber];
    
    if (!rules) return null;

    const predictions = [];
    const currentYear = new Date().getFullYear();
    
    // We check for 15 years from now
    for (let y = currentYear; y < currentYear + 15; y++) {
        const yearDigit = getSingleDigit(y);
        if (rules.marriage_years.includes(yearDigit)) {
            predictions.push({
                year: y,
                type: 'Primary Yoga',
                probability: 'High'
            });
        }
    }

    return {
        birthNumber,
        lifePathNumber,
        rules,
        predictions
    };
};
