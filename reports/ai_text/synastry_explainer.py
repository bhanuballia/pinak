def generate_synastry_reading(p1_name: str, p2_name: str, top_hits: list) -> str:
    """Generates an empathetic relationship reading based on geometric synastry aspects."""
    
    # Note: gemini-pro is deprecated and returns 404. Using gemini-flash-latest.
    model = genai.GenerativeModel('gemini-flash-latest')
    
    hits_text = ""
    for hit in top_hits:
        exact = "(EXACT)" if hit['is_exact'] else ""
        hits_text += f"- {p1_name}'s {hit['p1_body']} is in a {hit['aspect_name']} {exact} with {p2_name}'s {hit['p2_body']}.\n"

    prompt = f"""
    You are an expert, empathetic relationship astrologer specializing in psychological Synastry.
    I have calculated the exact geometric aspects between two people: {p1_name} and {p2_name}.

    Here are the most significant planetary connections (aspects) between their charts:
    {hits_text}

    Please write a comprehensive, beautifully formatted relationship reading analyzing these connections.
    Do NOT just list the aspects. Synthesize them into a cohesive narrative.
    
    Please structure your response with the following Markdown headings:
    ### 🌟 The Core Connection
    (Summarize the overall energetic flavor of this relationship based on the aspects).
    
    ### 💖 Communication & Affection
    (Analyze any hits involving Mercury, Venus, or the Moon).
    
    ### 🔥 Friction & Growth
    (Analyze any Squares, Oppositions, or hits involving Mars, Saturn, Rahu/Ketu).
    
    ### 💫 Final Verdict
    (A compassionate concluding thought).
    
    Keep the tone encouraging, deeply insightful, and psychologically profound. Do not use generic filler.
    """

    try:
        response = model.generate_content(prompt)
        return response.text
    except Exception as e:
        print(f"[SYNASTRY AI ERROR] {e} - Falling back to rule-based engine.")
        return generate_fallback_reading(p1_name, p2_name, top_hits)
