    comm = " ".join(list(dict.fromkeys(comm_text))) if comm_text else "Communication and affection in this relationship will rely on your ongoing mutual understanding and empathy."
    frict = " ".join(list(dict.fromkeys(frict_text))) if frict_text else "You have relatively few harsh frictional aspects, which suggests a smooth, easy-going dynamic."
    
