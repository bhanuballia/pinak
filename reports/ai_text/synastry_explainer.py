    reading += f"### 🔥 Friction & Growth\n{frict}\n\n"
    reading += f"### 💫 Final Verdict\nWhile the stars offer guidance, the success of your relationship is ultimately determined by the love, patience, and conscious effort you both invest. *(Note: This reading was generated by our built-in rule engine due to network/API unavailability)*."
    
