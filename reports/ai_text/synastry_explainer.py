def generate_fallback_reading(p1_name: str, p2_name: str, top_hits: list) -> str:
    """A rule-based fallback engine for when AI generation fails."""
    core_text = []
    comm_text = []
    frict_text = []
    
    for hit in top_hits:
        p1b = hit['p1_body']
        p2b = hit['p2_body']
        asp = hit['aspect_name']
        bodies = {p1b, p2b}
        
        # Core connection
        if "Sun" in bodies and "Moon" in bodies:
            if asp in ["Conjunction", "Trine", "Sextile"]:
                core_text.append(f"The {asp} between {p1_name}'s {p1b} and {p2_name}'s {p2b} creates a profound sense of familiarity and emotional alignment. You instinctively understand each other's core needs.")
            else:
                core_text.append(f"The {asp} between {p1_name}'s {p1b} and {p2_name}'s {p2b} shows an intense magnetism, though you may sometimes struggle to balance ego and emotions.")
        elif "Ascendant" in bodies:
            core_text.append(f"With an {asp} to the Ascendant, there is an immediate, noticeable physical and energetic dynamic between you.")
            
        # Communication & Affection
        if "Mercury" in bodies or "Venus" in bodies or ("Moon" in bodies and "Sun" not in bodies):
            if asp in ["Conjunction", "Trine", "Sextile"]:
                comm_text.append(f"A beautiful {asp} involving {p1b} and {p2b} suggests that your communication flows easily and affection is expressed naturally.")
            else:
                comm_text.append(f"The {asp} involving {p1b} and {p2b} means you may need to work a little harder to understand each other's love languages or communication styles, but the effort brings deep rewards.")
                
        # Friction & Growth
        if "Mars" in bodies or "Saturn" in bodies or "Rahu" in bodies or "Ketu" in bodies or asp in ["Square", "Opposition"]:
            if "Saturn" in bodies:
                frict_text.append(f"Saturn's involvement ({p1b} {asp} {p2b}) adds a serious, karmic tone. It provides 'glue' for a long-term bond, but can sometimes feel heavy or restrictive.")
            elif "Mars" in bodies:
                frict_text.append(f"The {asp} involving Mars brings a lot of heat and passion to the relationship, though it can also spark arguments if energy isn't channeled constructively.")
            elif "Rahu" in bodies or "Ketu" in bodies:
                frict_text.append(f"The Nodes (Rahu/Ketu) touching {p2b if p1b in ['Rahu','Ketu'] else p1b} indicates a fated, magnetic connection that pushes both of you to evolve.")
            else:
                frict_text.append(f"The {asp} between {p1b} and {p2b} is a point of friction, but it is precisely this tension that will help both of you grow.")

